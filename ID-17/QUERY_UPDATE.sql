--UPDATE
UPDATE SE2010 SE2
SET E2_TIPO = 'NF ',
    E2_XRENAV = 'ID15TIPONFE'
WHERE SE2.D_E_L_E_T_ = ' '
AND SE2.E2_TIPO = 'NFE'
AND SE2.E2_SALDO > 0
AND EXISTS (
    SELECT 1
    FROM P33010 P33
    WHERE SE2.E2_FILIAL = P33.P33_FILPS
    AND P33.P33_SIMP = 'S'
    AND P33.D_E_L_E_T_ = ' '
)
AND EXISTS (
    SELECT 1
    FROM SC7010 SC7
    WHERE SC7.C7_FILIAL = SE2.E2_FILIAL
    AND SC7.C7_XDOC = SE2.E2_NUM
    AND SC7.C7_XSERIE = SE2.E2_PREFIXO
    AND SC7.C7_FORNECE = SE2.E2_FORNECE
    AND SC7.C7_LOJA = SE2.E2_LOJA
    AND SC7.C7_XTPSP IN ('2', '3')
    AND SC7.C7_PRODUTO IN ('PRODEST', 'PRODNEST')
    AND SC7.D_E_L_E_T_ = ' '
);
 
--ROLLBACK
UPDATE SE2010 SE2
SET E2_TIPO = 'NFE',
    E2_XRENAV = ' '
WHERE SE2.D_E_L_E_T_ = ' '
AND SE2.E2_TIPO = 'NF '
AND SE2.E2_XRENAV = 'ID15TIPONFE';
 